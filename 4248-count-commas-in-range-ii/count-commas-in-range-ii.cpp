class Solution {
public:
    long long countCommas(long long n) {
        string s=to_string(n);
        int si=s.size();
        if(si<4) return 0;
        else if(si>=4 && si<=6) return n-999;
        else if(si>6 && si<=9) return (999999-999)+2*(n-999999);
        else if(si>9 && si<=12) return (999999-999)+2*(999999999-999999)+3*(n-999999999);
        else if(si>12 && si<=15) return (999999-999)+2*(999999999-999999)+3*(999999999999-999999999)+4*(n-999999999999);
        return (999999-999)+2*(999999999-999999)+3*(999999999999-999999999)+4*(999999999999999-999999999999)+5;
    }
};
